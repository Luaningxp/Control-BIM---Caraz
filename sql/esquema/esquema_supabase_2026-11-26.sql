CREATE OR REPLACE FUNCTION public.cambiar_grupo_masivo(p_ids bigint[], p_grupo text)
 RETURNS integer
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    v_grupo text;
    v_n     integer;
begin
    if not public.manpower_es_admin() then
        raise exception 'Solo los administradores pueden cambiar grupos en lote.';
    end if;
    if p_ids is null or cardinality(p_ids) = 0 then
        return 0;
    end if;

    if nullif(trim(coalesce(p_grupo, '')), '') is not null then
        select g.nombre into v_grupo
        from public.grupos_bim g
        where public.grupo_clave(g.nombre) = public.grupo_clave(p_grupo)
        limit 1;
        if v_grupo is null then
            raise exception 'El grupo "%" no existe en el catálogo.', p_grupo;
        end if;
    end if;

    update public.pendientes_bim
    set grupo = v_grupo
    where id = any (p_ids)
      and archivada_en is null
      and grupo is distinct from v_grupo;
    get diagnostics v_n = row_count;
    return v_n;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.check_manpower_diario()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
DECLARE
  total_dia NUMERIC;
BEGIN
  SELECT COALESCE(SUM(porcentaje_dia), 0) INTO total_dia
  FROM public.manpower_registros
  WHERE usuario_id = NEW.usuario_id 
    AND fecha = NEW.fecha
    AND id <> COALESCE(NEW.id, 0);
    
  IF (total_dia + NEW.porcentaje_dia) > 100 THEN
    RAISE EXCEPTION 'El porcentaje total del día no puede exceder 100%%. Ya tienes % registrado.', total_dia;
  END IF;
  
  RETURN NEW;
END;
$function$
