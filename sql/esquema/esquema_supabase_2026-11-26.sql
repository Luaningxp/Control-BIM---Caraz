CREATE OR REPLACE FUNCTION public.transicionar_cde(p_pendiente_id bigint, p_estado_nuevo text, p_aptitud_nueva text, p_comentario text DEFAULT NULL::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
  v_pendiente RECORD;
  v_rol TEXT;
  v_cargo TEXT;
  v_transicion_valida BOOLEAN := false;
BEGIN
  SELECT rol, cargo INTO v_rol, v_cargo FROM public.perfiles WHERE id = auth.uid();

  SELECT * INTO v_pendiente FROM public.pendientes_bim WHERE id = p_pendiente_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Contenedor no encontrado');
  END IF;

  -- Si es modelador y no es su tarea, rechazar
  IF v_cargo = 'Modelador BIM' AND v_pendiente.user_id <> auth.uid() THEN
    RETURN jsonb_build_object('ok', false, 'error', 'Sin permiso sobre este contenedor');
  END IF;

  -- REGLA: Solo admin o coordinador pueden sacar de Archived
  IF v_pendiente.estado_cde = 'Archived' AND p_estado_nuevo <> 'Archived' THEN
    IF v_rol NOT IN ('admin', 'coordinador_bim') AND v_cargo NOT IN ('BIM Manager', 'Coordinador BIM') THEN
      RETURN jsonb_build_object('ok', false, 'error', 'Solo Admin/Coordinador pueden sacar tareas de Archivado');
    END IF;
  END IF;

  -- Admin puede cualquier transición (excepto la regla anterior)
  IF v_rol = 'admin' OR v_cargo = 'BIM Manager' THEN
    v_transicion_valida := true;
  -- Transiciones válidas para Coordinadores y Supervisores
  ELSIF (v_rol = 'coordinador_bim' OR v_cargo = 'Coordinador BIM' OR v_cargo = 'Supervisor BIM') AND p_estado_nuevo <> 'Archived' THEN
     v_transicion_valida := true;
  -- Transiciones básicas para Modeladores
  ELSIF v_pendiente.estado_cde = 'WIP' AND p_estado_nuevo = 'Shared' THEN
    v_transicion_valida := true;
  ELSIF v_pendiente.estado_cde = 'Shared' AND p_estado_nuevo = 'WIP' THEN
    v_transicion_valida := true;
  END IF;

  IF NOT v_transicion_valida THEN
    RETURN jsonb_build_object('ok', false, 'error',
      format('Transición %s → %s no permitida', v_pendiente.estado_cde, p_estado_nuevo));
  END IF;

  UPDATE public.pendientes_bim
  SET estado_cde = p_estado_nuevo,
      codigo_aptitud = COALESCE(p_aptitud_nueva, codigo_aptitud),
      updated_at = NOW()
  WHERE id = p_pendiente_id;

  IF p_comentario IS NOT NULL THEN
    UPDATE public.transiciones_cde
    SET comentario = p_comentario
    WHERE id = (SELECT MAX(id) FROM public.transiciones_cde WHERE pendiente_id = p_pendiente_id);
  END IF;

  RETURN jsonb_build_object('ok', true);
END;
$function$
;

CREATE OR REPLACE FUNCTION public.trg_pendientes_linea_base()
 RETURNS trigger
 LANGUAGE plpgsql
AS $function$
begin
  if TG_OP = 'UPDATE' then
    NEW.fecha_inicio_original := coalesce(OLD.fecha_inicio_original, NEW.fecha_inicio_original, NEW.fecha_inicio_programado);
    NEW.fecha_fin_original    := coalesce(OLD.fecha_fin_original,    NEW.fecha_fin_original,    NEW.fecha_fin);
  else
    NEW.fecha_inicio_original := coalesce(NEW.fecha_inicio_original, NEW.fecha_inicio_programado);
    NEW.fecha_fin_original    := coalesce(NEW.fecha_fin_original,    NEW.fecha_fin);
  end if;
  return NEW;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.trg_validar_cierre_actividad()
 RETURNS trigger
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_rol text;
begin
  -- Permite operaciones de servidor / SQL Editor (sin usuario autenticado)
  if auth.uid() is null then
    return NEW;
  end if;

  if NEW.estado = 'Cerrado' then
    if NEW.fecha_cierre is null then
      raise exception 'No se puede cerrar la actividad sin Fecha de Cierre Real.';
    end if;

    if TG_OP = 'INSERT' or OLD.estado is distinct from 'Cerrado' then
      select lower(trim(rol)) into v_rol
      from public.perfiles where id = auth.uid();

      if v_rol is null or v_rol not in ('admin','coordinador_bim','supervisor_bim') then
        raise exception 'Solo supervisor, coordinador o BIM Manager pueden cerrar actividades.';
      end if;
    end if;
  end if;

  return NEW;
end;
$function$
;

CREATE OR REPLACE FUNCTION public.validar_guardado_tarea(p_id integer, p_payload jsonb, p_causas_ids integer[] DEFAULT '{}'::integer[])
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    v_estado TEXT;
    v_fecha_cierre DATE;
    v_fecha_fin DATE;
    v_causas_count INT;
BEGIN
    v_estado := p_payload->>'estado';
    v_fecha_cierre := NULLIF(p_payload->>'fecha_cierre', '')::DATE;
    v_fecha_fin := NULLIF(p_payload->>'fecha_fin', '')::DATE;
    v_causas_count := COALESCE(array_length(p_causas_ids, 1), 0);

    -- Regla 1: no cerrar sin fecha de cierre
    IF v_estado = 'Cerrado' AND v_fecha_cierre IS NULL THEN
        RETURN jsonb_build_object('ok', false, 'error', 'No se puede cerrar sin fecha de cierre');
    END IF;

    -- Regla 2: cierre tardío exige al menos 1 causa
    IF v_estado = 'Cerrado'
       AND v_fecha_cierre IS NOT NULL
       AND v_fecha_fin IS NOT NULL
       AND v_fecha_cierre > v_fecha_fin
       AND v_causas_count = 0 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'Cierre tardío requiere al menos 1 causa');
    END IF;

    -- Regla 3: máximo 5 causas
    IF v_causas_count > 5 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'Máximo 5 causas por tarea');
    END IF;

    -- Regla 4: estados válidos
    IF v_estado IS NOT NULL AND v_estado NOT IN
       ('No iniciado','En proceso','En espera','Reprogramado','Cerrado') THEN
        RETURN jsonb_build_object('ok', false, 'error', 'Estado inválido');
    END IF;

    RETURN jsonb_build_object('ok', true);
END;
$function$
;

