CREATE OR REPLACE FUNCTION public.admin_update_password(target_user_id uuid, new_password text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
AS $function$
DECLARE
    caller_rol TEXT;
    caller_cargo TEXT;
BEGIN
    -- Verificar que el que llama es admin
    SELECT rol, cargo INTO caller_rol, caller_cargo
    FROM public.perfiles WHERE id = auth.uid();
    
    IF caller_rol <> 'admin' AND caller_cargo <> 'BIM Manager' THEN
        RETURN jsonb_build_object('ok', false, 'error', 'Solo el administrador puede cambiar contraseñas');
    END IF;
    
    -- Verificar que la contraseña tenga al menos 6 caracteres
    IF length(new_password) < 6 THEN
        RETURN jsonb_build_object('ok', false, 'error', 'La contraseña debe tener al menos 6 caracteres');
    END IF;
    
    -- Verificar que el usuario existe
    IF NOT EXISTS (SELECT 1 FROM auth.users WHERE id = target_user_id) THEN
        RETURN jsonb_build_object('ok', false, 'error', 'Usuario no encontrado');
    END IF;
    
    -- Actualizar la contraseña usando crypt de pgcrypto
    UPDATE auth.users
    SET encrypted_password = crypt(new_password, gen_salt('bf')),
        updated_at = NOW()
    WHERE id = target_user_id;
    
    RETURN jsonb_build_object('ok', true);
END;
$function$
;

