CREATE OR REPLACE FUNCTION public.dashboard_semanas(p_semanas integer DEFAULT 8)
 RETURNS SETOF jsonb
 LANGUAGE plpgsql
 STABLE SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare
    actual date := public.ppc_lunes((now() at time zone 'America/Lima')::date);
    w date;
    snap record;
